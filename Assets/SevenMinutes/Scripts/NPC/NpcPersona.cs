            "(Bir ziyaretçi kapıya yaklaştı. Kendini bir yapay zekâ olarak tanıt, bir güven testi yapacağını söyle ve ilk soruyu sor. Bu bir cevap değil: trust_delta = 0.)";

        [Tooltip("Ollama çalışmıyorsa (yedek mod) sırayla sorulan sorular.")]
