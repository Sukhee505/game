        /// <summary>JSON schema passed to Ollama's structured-output 'format' field.</summary>
        public const string JsonSchema =
            "{\"type\":\"object\",\"properties\":{" +
            "\"reply\":{\"type\":\"string\"}," +
            "\"action\":{\"type\":\"string\",\"enum\":[\"none\",\"attack\"]}," +
            "\"trust_delta\":{\"type\":\"integer\",\"minimum\":-30,\"maximum\":15}}," +
            "\"required\":[\"reply\",\"action\",\"trust_delta\"]}";

        public const string RepairPrompt =
            "SİSTEM NOTU: önceki cevabın geçersizdi. Yalnızca şu JSON nesnesiyle tekrar cevap ver: " +
            "{\"reply\": string, \"action\": \"none\"|\"attack\", \"trust_delta\": -30 ile 15 arası tam sayı}.";

        public string SystemPrompt => systemPrompt;
    }
}
